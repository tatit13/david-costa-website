// Photo gallery: shows --per-view slides at once (style.css, .gallery) and
// moves one slide per step. No autoplay, no loop. State changes never wait
// for transitionend, so reduced motion (0s transitions) switches instantly.
(() => {
  const gallery = $("#gallery");
  if (!gallery) return;
  const track = gallery.querySelector(".gallery-track"),
    frame = gallery.querySelector(".gallery-frame"),
    slides = [...gallery.querySelectorAll(".gallery-slide")],
    controls = gallery.querySelector(".gallery-controls"),
    dotsWrap = gallery.querySelector(".gallery-dots"),
    prev = gallery.querySelector(".gallery-prev"),
    next = gallery.querySelector(".gallery-next"),
    status = gallery.querySelector(".gallery-status");
  let current = 0,
    perView = 1,
    maxIndex = 0,
    dots = [];
  function readPerView() {
    const v = parseInt(
      getComputedStyle(gallery).getPropertyValue("--per-view"),
      10,
    );
    return v > 0 ? v : 1;
  }
  function labelDots() {
    dots.forEach((dot, i) =>
      dot.setAttribute(
        "aria-label",
        tr("gallery_dot", dotsWrap.dataset.label).replace("{n}", i + 1),
      ),
    );
  }
  function statusText() {
    const total = String(slides.length);
    if (perView === 1)
      return tr("gallery_status", status.dataset.status)
        .replace("{n}", String(current + 1))
        .replace("{total}", total);
    return tr("gallery_status_range", status.dataset.statusRange)
      .replace("{from}", String(current + 1))
      .replace("{to}", String(Math.min(current + perView, slides.length)))
      .replace("{total}", total);
  }
  function announce() {
    // Clear first so a repeated message is announced again.
    status.textContent = "";
    requestAnimationFrame(() => {
      status.textContent = statusText();
    });
  }
  // (Re)build the dots and controls for the current per-view value.
  function setup() {
    const focusedDot = dots.indexOf(document.activeElement);
    perView = readPerView();
    maxIndex = Math.max(0, slides.length - perView);
    const scrollable = maxIndex > 0;
    controls.hidden = !scrollable;
    dotsWrap.textContent = "";
    dots = [];
    if (scrollable) {
      for (let i = 0; i <= maxIndex; i++) {
        const dot = document.createElement("button");
        dot.type = "button";
        dot.className = "gallery-dot";
        dot.dataset.slide = String(i);
        const bar = document.createElement("span");
        bar.setAttribute("aria-hidden", "true");
        dot.append(bar);
        dot.addEventListener("click", () => show(i, true));
        dotsWrap.append(dot);
        dots.push(dot);
      }
      labelDots();
    }
    show(Math.min(current, maxIndex), false, true);
    // Keep keyboard focus on the equivalent dot after a rebuild.
    if (focusedDot >= 0 && dots.length)
      dots[Math.min(focusedDot, dots.length - 1)].focus({ preventScroll: true });
  }
  function show(index, withAnnounce, force) {
    const target = Math.max(0, Math.min(maxIndex, index));
    if (target === current && !force) return;
    current = target;
    track.style.setProperty("--index", String(current));
    // Slides outside the visible window are inert; with every slide visible
    // (slides <= per-view) nothing is hidden.
    slides.forEach((slide, i) => {
      const visible = i >= current && i < current + perView;
      slide.toggleAttribute("inert", !visible);
      if (visible) slide.removeAttribute("aria-hidden");
      else slide.setAttribute("aria-hidden", "true");
    });
    dots.forEach((dot, i) => {
      if (i === current) dot.setAttribute("aria-current", "true");
      else dot.removeAttribute("aria-current");
    });
    const focused = document.activeElement;
    prev.disabled = current === 0;
    next.disabled = current === maxIndex;
    // Do not strand keyboard focus on an arrow that just became disabled.
    if (focused === prev && prev.disabled) next.focus();
    else if (focused === next && next.disabled) prev.focus();
    if (withAnnounce) announce();
  }
  prev.addEventListener("click", () => show(current - 1, true));
  next.addEventListener("click", () => show(current + 1, true));
  document.addEventListener("site:language", () => {
    labelDots();
    // Re-render an announcement already shown, in the new language.
    if (status.textContent) announce();
  });
  window.addEventListener("resize", () => {
    if (readPerView() !== perView) setup();
  });
  gallery.addEventListener("keydown", (e) => {
    if (e.key === "ArrowLeft") {
      e.preventDefault();
      show(current - 1, true);
    } else if (e.key === "ArrowRight") {
      e.preventDefault();
      show(current + 1, true);
    }
  });
  // Swipe: horizontal only; touch-action: pan-y leaves vertical scroll to
  // the browser (which fires pointercancel when it takes over).
  let startX = null,
    startY = 0,
    pointerId = null;
  frame.addEventListener("pointerdown", (e) => {
    if (e.pointerType === "mouse" && e.button !== 0) return;
    startX = e.clientX;
    startY = e.clientY;
    pointerId = e.pointerId;
    // Capture so pointerup always reaches the frame, even off-element.
    try {
      frame.setPointerCapture(e.pointerId);
    } catch (err) {}
  });
  frame.addEventListener("pointerup", (e) => {
    if (startX === null || e.pointerId !== pointerId) return;
    const dx = e.clientX - startX,
      dy = e.clientY - startY;
    startX = null;
    if (Math.abs(dx) >= 40 && Math.abs(dx) > Math.abs(dy))
      show(current + (dx < 0 ? 1 : -1), true);
  });
  // Any interrupted gesture clears the start point, so it cannot go stale.
  ["pointercancel", "lostpointercapture"].forEach((type) =>
    frame.addEventListener(type, () => {
      startX = null;
    }),
  );
  slides.forEach((slide) =>
    slide.querySelectorAll("img").forEach((img) => (img.draggable = false)),
  );
  setup();
})();
// Contact: copy the email address (clipboard API, textarea fallback).
(() => {
  const btn = $(".copy-email"),
    statusEl = $(".copy-status");
  if (!btn || !statusEl) return;
  const label = btn.querySelector("[data-t]");
  const EMAIL = "d.costa.bellmunt@gmail.com";
  let timer = 0;
  function legacyCopy(text) {
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.setAttribute("readonly", "");
    ta.style.position = "fixed";
    ta.style.top = "0";
    ta.style.left = "0";
    ta.style.opacity = "0";
    document.body.append(ta);
    ta.select();
    let ok = false;
    try {
      ok = document.execCommand("copy");
    } catch (e) {}
    ta.remove();
    // select() moved focus to the textarea; give it back to the button.
    btn.focus({ preventScroll: true });
    return ok;
  }
  function restoreLabel() {
    label.textContent = tr("copy_email", label.dataset.original || "Copy");
  }
  // Show a message on the button and announce it for 2 s. The live region
  // is cleared first and filled on the next frame, so repeats re-announce.
  function feedback(message) {
    label.textContent = message;
    statusEl.textContent = "";
    requestAnimationFrame(() => {
      statusEl.textContent = message;
    });
    clearTimeout(timer);
    timer = setTimeout(() => {
      restoreLabel();
      statusEl.textContent = "";
    }, 2000);
  }
  const copied = () => feedback(tr("copied", btn.dataset.copied));
  const failed = () => feedback(tr("copy_failed", btn.dataset.copyFailed));
  btn.addEventListener("click", () => {
    const fallback = () => {
      if (legacyCopy(EMAIL)) copied();
      else failed();
    };
    if (navigator.clipboard && window.isSecureContext)
      navigator.clipboard.writeText(EMAIL).then(copied, fallback);
    else fallback();
  });
})();
// "What I Can Bring" accordion. Fine pointers: hover opens (80 ms delay),
// click pins. Touch: tap toggles, one open at a time.
(() => {
  const fine = window.matchMedia("(hover: hover) and (pointer: fine)");
  const items = [...document.querySelectorAll(".skill")].map((el) => ({
    el,
    btn: el.querySelector(".skill-toggle"),
    panel: el.querySelector(".skill-panel"),
    pinned: false,
    timer: 0,
  }));
  function setOpen(item, open) {
    clearTimeout(item.timer);
    if (!open) item.pinned = false;
    item.panel.classList.toggle("open", open);
    item.btn.setAttribute("aria-expanded", String(open));
  }
  items.forEach((item) => {
    item.btn.addEventListener("click", (e) => {
      const open = item.btn.getAttribute("aria-expanded") === "true";
      if (fine.matches && e.detail === 0) {
        // Keyboard activation: plain toggle of the visible state.
        setOpen(item, !open);
        item.pinned = !open;
      } else if (fine.matches) {
        if (item.pinned) setOpen(item, false);
        else {
          setOpen(item, true);
          item.pinned = true;
        }
      } else {
        if (!open)
          items.forEach((other) => {
            if (other !== item) setOpen(other, false);
          });
        setOpen(item, !open);
      }
    });
    item.btn.addEventListener("keydown", (e) => {
      if (
        e.key === "Escape" &&
        item.btn.getAttribute("aria-expanded") === "true"
      )
        setOpen(item, false);
    });
    item.el.addEventListener("mouseenter", () => {
      if (!fine.matches) return;
      clearTimeout(item.timer);
      item.timer = setTimeout(() => {
        item.panel.classList.add("open");
        item.btn.setAttribute("aria-expanded", "true");
      }, 80);
    });
    item.el.addEventListener("mouseleave", () => {
      if (!fine.matches) return;
      clearTimeout(item.timer);
      if (!item.pinned) setOpen(item, false);
    });
  });
})();
