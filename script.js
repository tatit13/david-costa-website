document.querySelectorAll("[data-lang]").forEach((b) =>
  b.addEventListener("click", () => {
    const menuWasOpen = links.classList.contains("active");
    let anchor = null;
    try {
      anchor = captureReadingAnchor();
      // Stop Chrome's native scroll anchoring from compensating twice.
      if (anchor) document.documentElement.style.overflowAnchor = "none";
    } catch (e) {
      anchor = null;
    }
    try {
      setLanguage(b.dataset.lang);
      setMenuOpen(false);
      // The clicked button is now hidden; keep focus off <body>.
      if (menuWasOpen) menu.focus({ preventScroll: true });
      if (anchor && anchor.el.isConnected) {
        const delta = anchor.el.getBoundingClientRect().top - anchor.top;
        if (delta) scrollByInstant(delta);
      }
    } finally {
      // overflow-anchor: none must never stay on <html>.
      requestAnimationFrame(() => {
        document.documentElement.style.overflowAnchor = "";
      });
    }
  }),
);
document.addEventListener("keydown", (e) => {
  if (e.key !== "Escape") return;
  if (links.classList.contains("active")) {
    // Only reclaim focus if it was in the menu; never steal it from elsewhere.
    const active = document.activeElement;
    const focusInMenu = active === menu || links.contains(active);
    setMenuOpenKeepScroll(false, () => {
      if (focusInMenu) menu.focus({ preventScroll: true });
    });
  }
});
// Close only when focus moves to a real element outside the menu. A null
// relatedTarget (e.g. clicking a non-focusable area) is left to the
// document click handler below.
function closeMenuOnFocusLeave(e) {
  if (!links.classList.contains("active")) return;
  const next = e.relatedTarget;
  if (!next || menu.contains(next) || links.contains(next)) return;
  setMenuOpen(false);
}
menu.addEventListener("focusout", closeMenuOnFocusLeave);
links.addEventListener("focusout", closeMenuOnFocusLeave);
document.addEventListener("click", (e) => {
  if (
    links.classList.contains("active") &&
    !menu.contains(e.target) &&
    !links.contains(e.target)
  )
    setMenuOpenKeepScroll(false);
});
