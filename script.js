// Translation for the current <html lang>; English comes from the caller
// (read from the DOM), so EN stays in index.html.
function tr(key, en) {
  const code = document.documentElement.lang;
  return (code !== "en" && dict[code] && dict[code][key]) || en;
}
function setLanguage(code) {
  if (!["en", "es", "ca"].includes(code)) code = "en";
  document.documentElement.lang = code;
  // Document title and meta description: EN read from the DOM once.
  const metaDesc = document.querySelector('meta[name="description"]');
  const root = document.documentElement;
  if (root.dataset.originalTitle === undefined)
    root.dataset.originalTitle = document.title;
  document.title =
    code === "en"
      ? root.dataset.originalTitle
      : dict[code].meta_title || root.dataset.originalTitle;
  if (metaDesc) {
    if (metaDesc.dataset.original === undefined)
      metaDesc.dataset.original = metaDesc.getAttribute("content") || "";
    metaDesc.setAttribute(
      "content",
      code === "en"
        ? metaDesc.dataset.original
        : dict[code].meta_desc || metaDesc.dataset.original,
    );
  }
  document.querySelectorAll("[data-t]").forEach((el) => {
    if (!el.dataset.original) el.dataset.original = el.textContent;
    el.textContent =
      code === "en"
        ? el.dataset.original
        : dict[code][el.dataset.t] || el.dataset.original;
  });
  document.querySelectorAll("[data-t-alt]").forEach((el) => {
    if (!el.dataset.originalAlt) el.dataset.originalAlt = el.alt;
    el.alt =
      code === "en"
        ? el.dataset.originalAlt
        : dict[code][el.dataset.tAlt] || el.dataset.originalAlt;
  });
  // Static, trusted dictionary values only (markup such as <br>).
  document.querySelectorAll("[data-t-html]").forEach((el) => {
    if (el.dataset.originalHtml === undefined)
      el.dataset.originalHtml = el.innerHTML;
    el.innerHTML =
      code === "en"
        ? el.dataset.originalHtml
        : dict[code][el.dataset.tHtml] || el.dataset.originalHtml;
  });
  document.querySelectorAll("[data-t-aria]").forEach((el) => {
    if (el.dataset.originalAria === undefined)
      el.dataset.originalAria = el.getAttribute("aria-label") || "";
    el.setAttribute(
      "aria-label",
      code === "en"
        ? el.dataset.originalAria
        : dict[code][el.dataset.tAria] || el.dataset.originalAria,
    );
  });
  // Every CV link (hero button and CV band) points to the PDF for this language.
  const cvHref =
    {
      en: "documents/CV.pdf",
      es: "documents/CV-ES.pdf",
      ca: "documents/CV-CA.pdf",
    }[code] || "documents/CV.pdf";
  document.querySelectorAll("[data-cv]").forEach((link) => {
    link.setAttribute("href", cvHref);
    link.setAttribute("hreflang", code);
  });
  document.querySelectorAll("[data-lang]").forEach((b) => {
    if (b.dataset.lang === code) b.setAttribute("aria-current", "true");
    else b.removeAttribute("aria-current");
  });
  // Let components with generated text (gallery dots, live regions) re-render.
  document.dispatchEvent(new CustomEvent("site:language", { detail: code }));
  try {
    localStorage.setItem("david-language", code);
  } catch (e) {}
  setThemeLabel();
}
// The label is constant (data-t / data-t-aria); only the pressed state changes.
function setThemeLabel() {
  theme.setAttribute(
    "aria-pressed",
    String(document.body.classList.contains("dark")),
  );
}
function setMenuOpen(open) {
  links.classList.toggle("active", open);
  menu.setAttribute("aria-expanded", String(open));
}
// Instant scroll helpers: html has scroll-behavior: smooth, so the instant
// behaviour must be explicit.
// Legacy fallback: switch off CSS smooth scrolling for the call so the
// correction is not animated.
function withAutoScrollBehavior(fn) {
  const root = document.documentElement;
  root.style.scrollBehavior = "auto";
  try {
    fn();
  } finally {
    root.style.scrollBehavior = "";
  }
}
function scrollToInstant(y) {
  try {
    window.scrollTo({ top: y, behavior: "instant" });
  } catch (e) {
    withAutoScrollBehavior(() => window.scrollTo(window.scrollX, y));
  }
}
function scrollByInstant(dy) {
  try {
    window.scrollBy({ top: dy, behavior: "instant" });
  } catch (e) {
    withAutoScrollBehavior(() => window.scrollBy(0, dy));
  }
}
// Open/close the menu without moving the page (hamburger, Escape, outside
// click). Not used for in-page links or Tab-out, which may scroll by design.
function setMenuOpenKeepScroll(open, afterChange) {
  const y = window.scrollY;
  setMenuOpen(open);
  if (afterChange) afterChange();
  if (window.scrollY !== y) scrollToInstant(y);
}
// Reading-position anchor for user language changes: the first element of
// main/footer just below the sticky header (or the viewport top).
function captureReadingAnchor() {
  if (window.scrollY <= 0) return null;
  const header = document.querySelector("header");
  const topEdge =
    header && window.matchMedia("(min-width: 720.02px)").matches
      ? Math.max(0, header.getBoundingClientRect().bottom)
      : 0;
  const main = document.getElementById("main"),
    footer = document.querySelector("footer");
  const el = document
    .elementsFromPoint(window.innerWidth / 2, topEdge + 8)
    .find(
      (n) =>
        (main && n !== main && main.contains(n)) ||
        (footer && footer.contains(n)),
    );
  return el ? { el, top: el.getBoundingClientRect().top } : null;
}
